//! 16-byte sentinels used by the AC1009 (R11/R12) wire format.
//!
//! Unlike the modern (R13+) format, R11/R12 frames its variable-size
//! sub-sections — entities, block-entities, extra-entities, per-table
//! record arrays, and the auxiliary header — with two 16-byte
//! sentinel patterns: a BEGIN sentinel before the payload and an END
//! sentinel after. LibreDWG's decoder rejects the file outright when
//! a sentinel is missing or misaligned (see `decode_preR13_sentinel`
//! at `decode_r11.c:269-292`).
//!
//! The byte patterns below are the same values LibreDWG hard-codes in
//! `common.c::dwg_sentinel` (lines 128-215). They are NOT bytewise
//! XORs of each other — each pair was chosen empirically by
//! AutoDesk's R11 engineers, so we cannot derive them programmatically
//! and must reproduce them literally.

pub type Sentinel = [u8; 16];

