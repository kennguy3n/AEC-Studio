#[cfg(test)]
mod tests {
    use super::*;

    /// All sentinels are 16 bytes; spot-check the lengths.
    #[test]
    fn sentinels_are_sixteen_bytes() {
        let all: &[&Sentinel] = &[
            &ENTITIES_BEGIN,
            &ENTITIES_END,
            &BLOCK_BEGIN,
            &BLOCK_END,
            &LAYER_BEGIN,
            &LAYER_END,
            &STYLE_BEGIN,
            &STYLE_END,
            &LTYPE_BEGIN,
            &LTYPE_END,
            &VIEW_BEGIN,
            &VIEW_END,
            &UCS_BEGIN,
            &UCS_END,
            &VPORT_BEGIN,
            &VPORT_END,
            &APPID_BEGIN,
            &APPID_END,
            &DIMSTYLE_BEGIN,
            &DIMSTYLE_END,
            &VX_BEGIN,
            &VX_END,
            &BLOCK_ENTITIES_BEGIN,
            &BLOCK_ENTITIES_END,
            &EXTRA_ENTITIES_BEGIN,
            &EXTRA_ENTITIES_END,
            &AUXHEADER_BEGIN,
            &AUXHEADER_END,
        ];
        for s in all {
            assert_eq!(s.len(), 16);
        }
    }

    /// All sentinels are pairwise distinct: LibreDWG resynchronises
    /// by pattern-matching, so any collision would silently corrupt
    /// the decode.
    #[test]
    fn sentinels_are_distinct() {
        let all: Vec<&Sentinel> = vec![
            &ENTITIES_BEGIN,
            &ENTITIES_END,
            &BLOCK_BEGIN,
            &BLOCK_END,
            &LAYER_BEGIN,
            &LAYER_END,
            &STYLE_BEGIN,
            &STYLE_END,
            &LTYPE_BEGIN,
            &LTYPE_END,
            &VIEW_BEGIN,
            &VIEW_END,
            &UCS_BEGIN,
            &UCS_END,
            &VPORT_BEGIN,
            &VPORT_END,
            &APPID_BEGIN,
            &APPID_END,
            &DIMSTYLE_BEGIN,
            &DIMSTYLE_END,
            &VX_BEGIN,
            &VX_END,
            &BLOCK_ENTITIES_BEGIN,
            &BLOCK_ENTITIES_END,
            &EXTRA_ENTITIES_BEGIN,
            &EXTRA_ENTITIES_END,
            &AUXHEADER_BEGIN,
            &AUXHEADER_END,
        ];
        for (i, a) in all.iter().enumerate() {
            for (j, b) in all.iter().enumerate() {
                if i != j {
                    assert_ne!(a, b, "sentinel collision at {} vs {}", i, j);
                }
            }
        }
    }
}
