      // submit_matrix: one job per (camera × preset) pair, all sharing
      // one batch id. As with `renderEnqueue` above, empty *and*
      // unknown inputs are hard errors — the native side at
      // `BridgeService::render_enqueue_batch` rejects unknown preset
      // ids via `RenderPresetStore::get`; the in-process backend
      // rejects them at the same point so dev/Vitest matches
      // production.
      const presets: string[] =
        params.presetIds && params.presetIds.length > 0
          ? params.presetIds
          : params.presetId
            ? [params.presetId]
            : [];
      if (params.cameraIds.length === 0) {
        throw new Error("renderEnqueueBatch requires at least one camera id");
      }
      if (presets.length === 0) {
        throw new Error("renderEnqueueBatch requires at least one preset id");
      }
      for (const preset of presets) {
        if (!isBuiltInPresetId(preset)) {
          throw new Error(`unknown render preset id \`${preset}\``);
        }
      }
      const batchId = id("batch");
      const created: string[] = [];
      for (const cameraId of params.cameraIds) {
        for (const preset of presets) {
          const job: RenderJob = {
            jobId: id("job"),
            status: "queued",
            preset,
            progress: 0,
            cameraId,
            batchId,
          };
          jobs.unshift(job);
          created.push(job.jobId);
        }
      }
      return { batchId, jobIds: created };
