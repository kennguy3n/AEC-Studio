/**
 * Renderer-side warning threshold for IFC files (100 MB). Mirrors
 * the Rust constant `BIM_IMPORT_LARGE_FILE_THRESHOLD_BYTES` in
 * `crates/aec_bridge/src/service.rs` exactly so the in-process JS
 * fallback agrees with the native bridge on what counts as
 * "large". If the Rust constant changes, update this one in
 * lockstep — the bridge regression test
 * `bim_check_file_size_threshold_matches_summary_flag` pins both
 * values together.
 */
export const BIM_IMPORT_LARGE_FILE_THRESHOLD_BYTES = 100 * 1024 * 1024;

/**
 * Source of truth (TS side) for the built-in render preset ids that
 * the in-process backends and renderer-side mocks validate against.
 * Must stay in lockstep with `RenderPresetStore::default()` in
 * `crates/aec_render/src/preset.rs` — the Rust constructors
 * `RenderPreset::{quick, standard, high, studio, eevee_preview,
 * walkthrough, panorama}()` are the source of truth on the native
 * side. Pinned by the `built_in_preset_ids_match_native` regression
 * test in `apps/desktop/renderer/src/__tests__/bridge-catalogue.test.ts`
 * which loads the canonical id list from
 * `crates/aec_render/tests/preset_ids.json` (regenerated by
 * `cargo test -p aec_render preset_ids`) so adding or removing a
 * Rust-side preset without updating this constant fails CI.
 */
export const BUILT_IN_PRESET_IDS = [
  "quick",
  "standard",
  "high",
  "studio",
  "eevee_preview",
  "walkthrough",
  "panorama",
] as const;

export type BuiltInPresetId = (typeof BUILT_IN_PRESET_IDS)[number];

/**
 * Return true iff `id` is a built-in preset id recognised by the
 * native [`RenderPresetStore`]. The in-process backends use this to
 * reject typo'd preset ids at the same point the Rust side would,
 * preserving dev/production parity.
 */
export function isBuiltInPresetId(id: string): id is BuiltInPresetId {
  return (BUILT_IN_PRESET_IDS as readonly string[]).includes(id);
}

/**
 * 16-hex random id helper used by the in-process backend for ids that
 * the renderer treats as opaque (revision ids, draft ids, …). Uses
 * Node's crypto so id collisions are vanishingly unlikely even when
 * many revisions are created in rapid succession during tests.
 */
function randomId(): string {
  return crypto.randomBytes(8).toString("hex");
}

/**
 * Response shape for the AI plan request. The `parsed` field is
 * tool-specific structured data, used by panels that need to display
 * proposals before the user accepts or rejects the diff. It is always
 * a JSON-safe object so it can cross the IPC boundary; consumers cast
 * to a narrower tool-specific type (e.g. `LayoutSuggestionParsed`).
 */
export interface AiPlanResponse {
  diffId: string;
  /** Tool-specific parsed payload. `null` when no parse was produced. */
  parsed?: AiPlanParsed | null;
}

/**
 * Rich outcome surfaced by {@link BridgeBackend.aiAcceptDiff}.
 *
 * Devin Review flagged the previous `Promise<{ accepted: true }>`
 * shape as `ANALYSIS_0002`: the native napi `AiAcceptOutcomeJs`
 * already carries the full apply telemetry (op count, applied
 * count, per-op skip reasons, the command IDs the engine
 * journalled, and the AI audit chain head), but the adapter was
 * discarding all of it and surfacing a literal `true`. The
 * renderer cannot then show "Accepted 7 of 8 operations (1
 * skipped: unknown entity kind `lamp`)" without re-walking the
 * diff itself.
 *
 * The new shape preserves `accepted: true` so any existing
 * `outcome.accepted` checks still work, and exposes the full
 * telemetry alongside it. The in-process fallback returns a
 * shape with zeroed counts — it has no real diff registry, so
 * there is nothing to apply.
 */
export interface AiAcceptOutcome {
  accepted: true;
  diffId: string;
  /** Total operations the diff carried. */
  opCount: number;
  /** Subset that the converter mapped to a typed command and that
   *  the command engine successfully executed. */
  appliedCount: number;
  /** Per-op reasons the converter could not translate (unknown
   *  entity kind, missing required field, dangling target, ...). */
  skipped: Array<{ opIndex: number; reason: string }>;
  /** Command IDs the journal assigned to the applied operations,
   *  in batch order. Useful for selecting newly-created entities
   *  in the renderer right after Accept lands. */
  commandIds: string[];
  /** Hex-encoded BLAKE3 hash of the final entry in the AI audit
   *  chain after this acceptance was logged. */
  auditChainHead: string;
}

/**
 * Per-extension boot failure surfaced by
 * {@link BridgeBackend.extensionsListLoadDiagnostics}. The Rust
 * bridge captures one of these every time
 * `BridgeService::new` encounters a broken extension during the
 * fault-tolerant boot path and the Settings page renders them as
 * a read-only diagnostics card.
 *
 * The wire format is stable across releases — adding a new
 * {@link ExtensionLoadDiagnostic.stage} value is additive (the
 * renderer falls back to the raw stage string) but renaming an
 * existing value is a breaking change.
 */
export interface ExtensionLoadDiagnostic {
  /**
   * The extension's manifest `id`, or `null` if the failure
   * happened before the manifest could be parsed (e.g. unreadable
   * file, syntactically invalid JSON).
   */
  extensionId: string | null;
  /**
   * On-disk path of the extension directory (or the manifest file
   * itself, for parse-stage failures). UTF-8 string with the
   * platform's native separators.
   */
  path: string;
  /**
   * Stable wire tag for the boot pipeline stage at which the
   * failure surfaced — one of:
   *
   * - `manifest_read` — couldn't open `manifest.json`
   * - `manifest_parse` — JSON syntax error
   * - `manifest_validation` — manifest violates structural
   *   invariants (missing required body, empty id, …)
   * - `unsafe_path` — manifest references a path outside the
   *   extension directory
   * - `signature_verification` — signature missing, malformed, or
   *   the public key isn't trusted
   * - `duplicate_id` — another loaded extension already claimed
   *   this id
   * - `asset_pack_install` — asset-pack host couldn't materialise
   *   the pack (missing blob, BLAKE3 mismatch, permission denied)
   * - `ai_tool_resolution` — AI-tool host couldn't resolve the
   *   tool (unknown scope, missing body, permission denied)
   *
   * New stages may be added in future versions; the renderer
   * shows the raw string when it doesn't recognise the value.
   */
  stage: string;
  /**
   * Human-readable error string from the underlying typed
   * error's `Display` impl. Suitable for showing as the
   * diagnostic detail without further interpretation.
   */
  message: string;
}

/**
 * Rich outcome surfaced by {@link BridgeBackend.aiRejectDiff}.
 *
 * Mirrors the accept outcome shape so the renderer can use a
 * single "diff lifecycle" toast for both paths. The reject path
 * never applies graph mutations, so it does not carry the
 * applied/skipped/command-id fields.
 */
export interface AiRejectOutcome {
  rejected: true;
  diffId: string;
  /** Total operations the rejected diff carried. */
  opCount: number;
  /** Free-form reason the renderer supplied. Logged to the AI
   *  audit chain so the provenance UI can show *why* a proposal
   *  was rejected. `null` when no reason was supplied. */
  reason: string | null;
  /** Hex-encoded BLAKE3 hash of the final entry in the AI audit
   *  chain after this rejection was logged. */
  auditChainHead: string;
}

/** Lowercase tier slug for the Ternary-Bonsai text models. */
export type AiModelTierSlug = "small" | "medium" | "large";

/** One row in {@link AiModelAvailability}. */
export interface AiModelTierInfo {
  tier: AiModelTierSlug;
  /** Human-readable name, e.g. `"Ternary-Bonsai 1.7B (1.58-bit GGUF Q2_0)"`. */
  name: string;
  /** Filename inside `modelsDir`. */
  filename: string;
  /** Expected file size (from the HuggingFace LFS pointer). */
  sizeBytes: number;
  /** `true` iff the file exists and its length matches `sizeBytes`. */
  available: boolean;
  /** Actual on-disk byte length. 0 when the file is missing. */
  sizeOnDisk: number;
}

/** Snapshot of all three text-model tiers + the active tier. */
export interface AiModelAvailability {
  tiers: AiModelTierInfo[];
  activeTier: AiModelTierSlug;
  /** Absolute path to the directory the bridge stores GGUFs in. */
  modelsDir: string;
}

/** Live progress snapshot of an in-flight model download. */
export interface AiDownloadProgress {
  tier: AiModelTierSlug;
  downloaded: number;
  total: number;
  /** One of `"downloading" | "verifying" | "completed" | "failed"`. */
  state: "downloading" | "verifying" | "completed" | "failed";
  /** Populated on `"failed"`; cleared on every other state. */
  message: string | null;
}

/** Successful return of {@link BridgeBackend.aiDownloadModel}. */
export interface AiDownloadResult {
  tier: AiModelTierSlug;
  /** Absolute on-disk path of the verified GGUF. */
  path: string;
  sizeBytes: number;
}

